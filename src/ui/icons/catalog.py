@lru_cache(maxsize=128)
def _render_icon(name: str, size: int, color: str, dpr: float) -> QIcon:
    """内部缓存渲染器 — 相同参数不重复渲染 SVG。"""
    svg_str = _SVG.get(name)
    if not svg_str:
        return QIcon()

    svg_str = svg_str.replace('stroke="currentColor"', f'stroke="{color}"')
    svg_str = svg_str.replace('fill="currentColor"', f'fill="{color}"')

    physical = int(size * dpr)
    renderer = QSvgRenderer(QByteArray(svg_str.encode("utf-8")))
    pixmap = QPixmap(physical, physical)
    pixmap.fill(Qt.transparent)
    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.Antialiasing, True)
    painter.setRenderHint(QPainter.SmoothPixmapTransform, True)
    renderer.render(painter)
    painter.end()
    pixmap.setDevicePixelRatio(dpr)
    return QIcon(pixmap)


def get_icon(
    name: str,
    size: int = 20,
    color: str | None = None,
) -> QIcon:
    """将 Lucide SVG 转为 QIcon，可指定尺寸和颜色。

    内部使用 LRU 缓存，主题切换时需调用 invalidate_icon_cache()。

    Args:
        name: 图标名（_SVG 字典的 key）
        size: 逻辑像素尺寸
        color: hex 颜色，None 则使用主题 icon_primary
    """
    if color is None:
        color = get_theme().icon_primary

    app = QApplication.instance()
    dpr = app.devicePixelRatio() if app else 1.0

    return _render_icon(name, size, color, dpr)


def get_icon_names() -> list[str]:
    """返回所有可用图标名。"""
    return list(_SVG.keys())


def invalidate_icon_cache() -> None:
    """主题切换时调用，清空图标渲染缓存。"""
    _render_icon.cache_clear()


def get_app_logo(size: int = 24) -> QIcon:
    """渲染 App 专属 Logo (app_logo.svg)，双色跟随主题。

    SVG 中使用语义占位符（不依赖具体 hex 值）:
        __LOGO_DARK__  → theme.logo_dark
        __LOGO_LIGHT__ → theme.logo_light
    """

    svg_path = Path(__file__).parent / "app_logo.svg"
    if not svg_path.exists():
        return QIcon()

    svg_str = svg_path.read_text(encoding="utf-8")

    # 语义占位符替换: 不依赖具体 hex 色号
    t = get_theme()
    svg_str = svg_str.replace("__LOGO_DARK__", t.logo_dark)
    svg_str = svg_str.replace("__LOGO_LIGHT__", t.logo_light)

    # Hi-DPI 渲染（正方形 SVG）
    app = QApplication.instance()
    dpr = app.devicePixelRatio() if app else 1.0
    physical = int(size * dpr)

    renderer = QSvgRenderer(QByteArray(svg_str.encode("utf-8")))
    pixmap = QPixmap(physical, physical)
    pixmap.fill(Qt.transparent)
    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.Antialiasing, True)
    painter.setRenderHint(QPainter.SmoothPixmapTransform, True)
    renderer.render(painter)
    painter.end()
    pixmap.setDevicePixelRatio(dpr)

    return QIcon(pixmap)
